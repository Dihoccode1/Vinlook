import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildInventory, repositoryRoot } from './inventory.mjs';

/** Public repository evidence only. No current state or completion is inferred. */
export function buildReadiness() {
  const inventory = buildInventory();
  const byLocale = inventory.registry.locales.map(languageCode => {
    const rows = inventory.rows.filter(row => row.languageCode === languageCode);
    return { languageCode, execution: rows[0].execution, pairsToRead: rows.length,
      historicalOnly: rows.filter(row => row.historicalApprovalReported).length,
      translationTasksIfAllMissing: rows.filter(row => row.translationModel !== null).length,
      audioTasksIfAllMissing: rows.length };
  });
  return { evidence: 'repository_only_not_live_acceptance', freshPairsVerified: 0,
    exactRemainingJobs: null, providerCallBudget: null, liveExecutionImplemented: false,
    pairsToRead: inventory.rows.length, historicalOnly: inventory.summary.historicalApprovalReports,
    withoutHistoricalReport: inventory.rows.filter(row => !row.historicalApprovalReported).length,
    fullListeningSeconds: { minimum: inventory.rows.length * 90, maximum: inventory.rows.length * 150 },
    pois: inventory.pois, byLocale,
    matrix: inventory.pois.map(poi => ({ poiRef: poi.poiRef, cells: inventory.registry.locales.map(languageCode => {
      const row = inventory.rows.find(row => row.poiRef === poi.poiRef && row.languageCode === languageCode);
      return { languageCode, action: row.historicalApprovalReported ? 'preserve_report_and_revalidate' : 'read_current_state' };
    }) })) };
}

export function readinessMarkdown() {
  const value = buildReadiness();
  const lines = ['# TU03 gap register — repository evidence only', '',
    'Generated by `node scripts/poc/content/readiness.mjs`. Refs #73 and #81.', '',
    `${value.pairsToRead} pairs need current private readback; ${value.freshPairsVerified} were freshly verified by this report.`,
    `${value.historicalOnly} pairs have historical approval reports; ${value.withoutHistoricalReport} have no such report.`,
    'Neither count establishes missing output. Exact remaining jobs and provider call',
    'budget are **unknown**. This tool implements no live execution.', '',
    '## Every POI and locale', '',
    'R = preserve historical report and revalidate; U = read current state.',
    'Both require private text/audio versions, hashes, duration, model and human',
    'review evidence. No cell means generate, reset review or publish.', '',
    `| POI | ${value.byLocale.map(row => row.languageCode).join(' | ')} |`,
    `| --- | ${value.byLocale.map(() => '---').join(' | ')} |`];
  for (const row of value.matrix) lines.push(`| ${row.poiRef} | ${row.cells.map(cell => cell.action === 'preserve_report_and_revalidate' ? 'R' : 'U').join(' | ')} |`);
  lines.push('', '## Source and media gaps by POI', '',
    'All 15 thumbnails lack verified license/provenance in this inventory; all 15',
    'arrival references remain desktop proposals requiring a review disposition.',
    'Fieldwork was waived, not performed. Source statements below are repository',
    'statements, not fresh human approval. Follow the linked source review for each POI.', '',
    '| POI | Name | Repository source statement | Source review | Thumbnail | Arrival |',
    '| --- | --- | --- | --- | --- | --- |');
  for (const poi of value.pois) lines.push(`| ${poi.poiRef} | ${poi.nameEN} | ${poi.repositoryEditorialStatement} | [review](../../../../${poi.sourceReviewFile}) | unverified | review needed |`);
  lines.push('', '## Locale work ceilings — not call quotas or job orders', '',
    'If every pair were absent: 225 translation tasks plus 240 audio tasks',
    '(60 server-adapter / 180 local-worker). Existing output must be subtracted',
    'only after private readback. One task can involve multiple provider/media',
    'requests and translation completion can enqueue audio automatically.', '',
    '| Locale | Audio execution | Pairs to read | Historical reports | Translation tasks if all absent | Audio tasks if all absent |',
    '| --- | --- | ---: | ---: | ---: | ---: |');
  for (const row of value.byLocale) lines.push(`| ${row.languageCode} | ${row.execution} | ${row.pairsToRead} | ${row.historicalOnly} | ${row.translationTasksIfAllMissing} | ${row.audioTasksIfAllMissing} |`);
  lines.push('', '## Review effort and next decisions', '',
    `One full listen to all 240 accepted-duration clips is ${value.fullListeningSeconds.minimum}–${value.fullListeningSeconds.maximum} seconds (6–10 reviewer-hours).`,
    'This excludes text/source review, corrections, replay, reviewer handoffs and',
    'generation time. It is a workload calculation, not a completion estimate or',
    'claim that all audio is available. Reviewers for the 16 languages need assignment.', '',
    'Source-review gaps for POI006–015, thumbnail permission, arrival decisions,',
    'fresh POI mapping/versions, exact quotas and worker state block a real batch.',
    'See [batch-plan.md](batch-plan.md) for the proposed read-only inventory, pilot,',
    'stop conditions and approval fields. Issue closure/PR merge does not supply',
    'the missing live evidence. No provider, login, upload or deployment was called.', '');
  return lines.join('\n');
}

export async function main(args) {
  if (args.length > 1 || args.length === 1 && args[0] !== '--check') throw new Error('INVALID_COMMAND');
  const target = resolve(repositoryRoot, 'docs/poc/tu/content/readiness.md'), expected = readinessMarkdown();
  if (args[0] === '--check') {
    if ((await readFile(target, 'utf8')).replace(/\r\n/g, '\n') !== expected) throw new Error('READINESS_OUTDATED');
  } else await writeFile(target, expected);
  console.log(JSON.stringify({ mode: 'repository_only', checked: args[0] === '--check', pairsToRead: 240, liveExecuted: false }));
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { await main(process.argv.slice(2)); }
  catch (error) { console.error(JSON.stringify({ error: ['INVALID_COMMAND', 'READINESS_OUTDATED'].includes(error.message) ? error.message : 'READINESS_FAILED' })); process.exitCode = 1; }
}
