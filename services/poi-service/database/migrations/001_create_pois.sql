CREATE TABLE dbo.Pois (
    Id UNIQUEIDENTIFIER NOT NULL CONSTRAINT PK_Pois PRIMARY KEY,
    Slug NVARCHAR(160) NOT NULL CONSTRAINT UQ_Pois_Slug UNIQUE,
    Name NVARCHAR(200) NOT NULL,
    Description NVARCHAR(MAX) NOT NULL,
    Address NVARCHAR(500) NOT NULL,
    Latitude FLOAT NOT NULL CONSTRAINT CK_Pois_Latitude CHECK (Latitude BETWEEN -90 AND 90),
    Longitude FLOAT NOT NULL CONSTRAINT CK_Pois_Longitude CHECK (Longitude BETWEEN -180 AND 180),
    Category NVARCHAR(50) NOT NULL,
    SourceLanguage VARCHAR(10) NOT NULL CONSTRAINT DF_Pois_Language DEFAULT 'vi',
    IsPublished BIT NOT NULL CONSTRAINT DF_Pois_Published DEFAULT 0,
    CreatedAt DATETIME2 NOT NULL CONSTRAINT DF_Pois_Created DEFAULT SYSUTCDATETIME(),
    UpdatedAt DATETIME2 NOT NULL CONSTRAINT DF_Pois_Updated DEFAULT SYSUTCDATETIME()
);
CREATE INDEX IX_Pois_Published_Category ON dbo.Pois (IsPublished, Category);
