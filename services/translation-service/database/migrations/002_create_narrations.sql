CREATE TABLE dbo.PoiNarrations (
  PoiId UNIQUEIDENTIFIER NOT NULL,
  LanguageCode VARCHAR(10) NOT NULL,
  ContentHash CHAR(64) NOT NULL,
  Audio VARBINARY(MAX) NOT NULL,
  CreatedAt DATETIME2 NOT NULL DEFAULT SYSUTCDATETIME(),
  CONSTRAINT PK_PoiNarrations PRIMARY KEY (PoiId, LanguageCode),
  CONSTRAINT CK_PoiNarrations_AudioSize CHECK (DATALENGTH(Audio) BETWEEN 44 AND 21000000)
);
