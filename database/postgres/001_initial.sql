CREATE SCHEMA IF NOT EXISTS vinlook;
SET search_path TO vinlook,public;
CREATE COLLATION IF NOT EXISTS vinlook.case_insensitive(provider=icu,locale='und-u-ks-level2',deterministic=false);
CREATE OR REPLACE FUNCTION next_code(prefix text, sequence_name text) RETURNS text LANGUAGE plpgsql AS $$
DECLARE n bigint;
BEGIN n:=nextval(sequence_name::regclass); RETURN prefix||CASE WHEN n<1000 THEN lpad(n::text,3,'0') ELSE n::text END; END $$;
CREATE SEQUENCE IF NOT EXISTS users_id_seq;
CREATE SEQUENCE IF NOT EXISTS pois_id_seq;
CREATE SEQUENCE IF NOT EXISTS visit_sessions_id_seq;
CREATE SEQUENCE IF NOT EXISTS poi_translations_id_seq;
CREATE SEQUENCE IF NOT EXISTS poi_narrations_id_seq;
CREATE TABLE users (
 id varchar(36) COLLATE vinlook.case_insensitive PRIMARY KEY DEFAULT next_code('USR','users_id_seq'),username varchar(100) NOT NULL,
 password_hash varchar(200) NOT NULL,full_name varchar(200) NOT NULL,
 role varchar(20) NOT NULL DEFAULT 'admin' CHECK(role IN ('admin','staff')),
 status varchar(20) NOT NULL DEFAULT 'active' CHECK(status IN ('active','disabled')),
 created_at timestamptz NOT NULL DEFAULT now(),failed_login_count int NOT NULL DEFAULT 0 CHECK(failed_login_count BETWEEN 0 AND 15),
 login_retry_at timestamptz,login_locked boolean NOT NULL DEFAULT false
);
CREATE UNIQUE INDEX users_username ON users(lower(username));
CREATE TABLE admin_sessions (
 token_hash char(64) PRIMARY KEY,user_id varchar(36) COLLATE vinlook.case_insensitive NOT NULL REFERENCES users(id),
 created_at timestamptz NOT NULL DEFAULT now(),expires_at timestamptz NOT NULL,revoked_at timestamptz
);
CREATE INDEX admin_sessions_user ON admin_sessions(user_id,expires_at);
CREATE TABLE pois (
 id varchar(36) COLLATE vinlook.case_insensitive PRIMARY KEY DEFAULT next_code('POI','pois_id_seq'),slug varchar(160) NOT NULL,
 name varchar(200) NOT NULL,description text NOT NULL,visitor_description varchar(3000) NOT NULL DEFAULT '',
 address varchar(500) NOT NULL,latitude double precision NOT NULL CHECK(latitude BETWEEN -90 AND 90),
 longitude double precision NOT NULL CHECK(longitude BETWEEN -180 AND 180),category varchar(50) NOT NULL,
 source_language varchar(10) NOT NULL DEFAULT 'vi',is_published boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT date_trunc('milliseconds',now()),updated_at timestamptz NOT NULL DEFAULT date_trunc('milliseconds',now()),
 image_url text,image_credit varchar(300),image_source_url text,image_license_url text,
 created_by varchar(36) COLLATE vinlook.case_insensitive REFERENCES users(id),updated_by varchar(36) COLLATE vinlook.case_insensitive REFERENCES users(id)
);
CREATE UNIQUE INDEX pois_slug ON pois(lower(slug));
CREATE INDEX pois_published_category ON pois(is_published,category);
CREATE TABLE poi_images (
 poi_id varchar(36) COLLATE vinlook.case_insensitive PRIMARY KEY REFERENCES pois(id) ON DELETE CASCADE,content bytea NOT NULL,
 content_type varchar(30) NOT NULL,sha256 char(64) NOT NULL,updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE visit_sessions (
 id varchar(36) COLLATE vinlook.case_insensitive PRIMARY KEY DEFAULT next_code('VST','visit_sessions_id_seq'),started_at timestamptz NOT NULL DEFAULT now(),
 last_seen_at timestamptz NOT NULL DEFAULT now(),ended_at timestamptz,preferred_language varchar(10)
);
CREATE TABLE usage_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session_id varchar(36) COLLATE vinlook.case_insensitive NOT NULL REFERENCES visit_sessions(id),
 poi_id varchar(36) COLLATE vinlook.case_insensitive REFERENCES pois(id),event_type varchar(30) NOT NULL CHECK(event_type IN ('poi_view','audio_start','audio_pause','audio_end','route_created')),
 language_code varchar(10),occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE system_logs (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id varchar(36) COLLATE vinlook.case_insensitive REFERENCES users(id),poi_id varchar(36) COLLATE vinlook.case_insensitive REFERENCES pois(id),
 component varchar(100) NOT NULL,level varchar(10) NOT NULL CHECK(level IN ('info','warning','error')),
 action varchar(50),message varchar(2000) NOT NULL,occurred_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX system_logs_time ON system_logs(occurred_at,level);
CREATE TABLE poi_translations (
 id varchar(36) COLLATE vinlook.case_insensitive NOT NULL UNIQUE DEFAULT next_code('TRN','poi_translations_id_seq'),poi_id varchar(36) COLLATE vinlook.case_insensitive NOT NULL,
 language_code varchar(10) NOT NULL,source_language varchar(10) NOT NULL,source_hash char(64) NOT NULL,
 name varchar(2000) NOT NULL,description text NOT NULL,provider varchar(50) NOT NULL,translated_at timestamptz NOT NULL,
 status varchar(20) NOT NULL DEFAULT 'ready' CHECK(status IN ('ready','draft','failed')),PRIMARY KEY(poi_id,language_code)
);
CREATE TABLE poi_narrations (
 id varchar(36) COLLATE vinlook.case_insensitive NOT NULL UNIQUE DEFAULT next_code('AUD','poi_narrations_id_seq'),poi_id varchar(36) COLLATE vinlook.case_insensitive NOT NULL,
 language_code varchar(10) NOT NULL,content_hash char(64) NOT NULL,audio bytea,
 storage_path text,bytes int NOT NULL DEFAULT 0,created_at timestamptz NOT NULL DEFAULT now(),file_path varchar(1000),
 duration_seconds double precision CHECK(duration_seconds>=0),status varchar(20) NOT NULL DEFAULT 'ready' CHECK(status IN ('ready','draft','failed')),
 PRIMARY KEY(poi_id,language_code),CHECK(audio IS NOT NULL OR storage_path IS NOT NULL)
);
CREATE TABLE deployment_state (id int PRIMARY KEY CHECK(id=1),dataset_id uuid NOT NULL,source_sha256 char(64) NOT NULL,imported_at timestamptz NOT NULL DEFAULT now());
-- Backend connects through a private schema. No anonymous or authenticated Data API grants.
REVOKE ALL ON SCHEMA vinlook FROM PUBLIC;
DO $$ DECLARE t record; BEGIN FOR t IN SELECT tablename FROM pg_tables WHERE schemaname='vinlook' LOOP
 EXECUTE format('ALTER TABLE vinlook.%I ENABLE ROW LEVEL SECURITY',t.tablename);
END LOOP; END $$;
